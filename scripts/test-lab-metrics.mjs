import assert from 'node:assert/strict';
import {classificationMetrics, differenceInDifferences} from '../lib/lab-metrics.ts';
import {practiceCases,studySources} from '../data/lab-study.ts';
const initial=classificationMetrics(80,20,20,880);
assert.equal(initial.precision,0.8);
assert.equal(initial.recall,0.8);
assert.equal(initial.fpr,20/900);
assert.equal(initial.falseDiscovery,0.2);
assert.deepEqual(classificationMetrics(0,0,0,0),{precision:null,recall:null,fpr:null,falseDiscovery:null});
assert.equal(classificationMetrics(0,0,10,90).recall,0);
assert.equal(classificationMetrics(0,0,10,90).precision,null);
assert.equal(classificationMetrics(0,10,0,90).precision,0);
assert.throws(()=>classificationMetrics(-1,1,1,1));
assert.throws(()=>classificationMetrics(0.5,1,1,1));
assert.equal(differenceInDifferences(12,8,10,7),-1);
assert.equal(new Set(practiceCases.map(c=>c.id)).size,practiceCases.length);
assert(practiceCases.every(c=>Number.isInteger(c.answer)&&c.answer>=0&&c.answer<c.options.length));
assert(studySources.every(s=>s.url.startsWith('https://')));
console.log('Lab metrics, zero denominators, case answers and source links passed.');
